// もじと ことばの データ
(function () {
  // あいうえお表（たて＝だん、よこ＝ぎょう）。'' は あき。
  const BASIC_COLS = [
    'あいうえお', 'かきくけこ', 'さしすせそ', 'たちつてと', 'なにぬねの',
    'はひふへほ', 'まみむめも', 'や ゆ よ', 'らりるれろ', 'わ を  ', 'ん    ',
  ];
  const EXTRA_COLS = [
    'がぎぐげご', 'ざじずぜぞ', 'だぢづでど', 'ばびぶべぼ', 'ぱぴぷぺぽ',
    'ぁぃぅぇぉ', 'ゃ ゅ ょ', 'っ    ',
  ];
  const cols = s => [...s].map(c => (c === ' ' ? '' : c));

  const toKata = s => [...s].map(c => {
    const p = c.codePointAt(0);
    return p >= 0x3041 && p <= 0x3096 ? String.fromCodePoint(p + 0x60) : c;
  }).join('');
  const toHira = s => [...s].map(c => {
    const p = c.codePointAt(0);
    return p >= 0x30a1 && p <= 0x30f6 ? String.fromCodePoint(p - 0x60) : c;
  }).join('');

  const BASIC = BASIC_COLS.join('').replace(/ /g, '');
  const DAKU = EXTRA_COLS.slice(0, 5).join('');
  const SMALL = 'ぁぃぅぇぉゃゅょっ';

  // ことば（えもじ つき）。ひらがなモードと カタカナモードで べつの リスト。
  const HIRA_WORDS = [
    ['いぬ', '🐶'], ['ねこ', '🐱'], ['うし', '🐮'], ['うま', '🐴'], ['さる', '🐵'],
    ['とり', '🐦'], ['くま', '🐻'], ['たこ', '🐙'], ['かに', '🦀'], ['へび', '🐍'],
    ['かめ', '🐢'], ['あり', '🐜'], ['はち', '🐝'], ['いか', '🦑'], ['さかな', '🐟'],
    ['りす', '🐿️'], ['ぶた', '🐷'], ['かえる', '🐸'], ['ひよこ', '🐤'], ['うさぎ', '🐰'],
    ['きつね', '🦊'], ['しか', '🦌'], ['わに', '🐊'], ['くじら', '🐋'], ['ねずみ', '🐭'],
    ['ぞう', '🐘'], ['きりん', '🦒'], ['いちご', '🍓'], ['りんご', '🍎'], ['みかん', '🍊'],
    ['すいか', '🍉'], ['もも', '🍑'], ['くり', '🌰'], ['ぶどう', '🍇'], ['おにぎり', '🍙'],
    ['すし', '🍣'], ['たまご', '🥚'], ['ゆき', '⛄'], ['ほし', '⭐'], ['つき', '🌙'],
    ['はな', '🌷'], ['き', '🌳'], ['やま', '⛰️'], ['うみ', '🌊'], ['ふね', '🚢'],
    ['くつ', '👟'], ['いえ', '🏠'], ['て', '✋'], ['め', '👀'], ['みみ', '👂'],
    ['くち', '👄'], ['かさ', '☂️'], ['ほん', '📖'], ['えんぴつ', '✏️'], ['とけい', '⏰'],
    ['かぎ', '🔑'], ['おに', '👹'], ['たいこ', '🥁'], ['くるま', '🚗'], ['ひこうき', '✈️'],
    ['でんしゃ', '🚃'], ['じてんしゃ', '🚲'], ['にじ', '🌈'], ['くも', '☁️'], ['あめ', '☔'],
  ];
  const KATA_WORDS = [
    ['パン', '🍞'], ['バス', '🚌'], ['ケーキ', '🍰'], ['ライオン', '🦁'], ['ペンギン', '🐧'],
    ['コアラ', '🐨'], ['パンダ', '🐼'], ['トマト', '🍅'], ['バナナ', '🍌'], ['メロン', '🍈'],
    ['ピザ', '🍕'], ['アイス', '🍦'], ['テレビ', '📺'], ['ピアノ', '🎹'], ['ギター', '🎸'],
    ['ボール', '⚽'], ['ロボット', '🤖'], ['ロケット', '🚀'], ['タクシー', '🚕'], ['トラック', '🚚'],
    ['ゴリラ', '🦍'], ['カメラ', '📷'], ['ハート', '❤️'], ['ドーナツ', '🍩'], ['レモン', '🍋'],
    ['キウイ', '🥝'], ['スプーン', '🥄'], ['ベッド', '🛏️'], ['シャツ', '👕'], ['ラッパ', '🎺'],
    ['トナカイ', '🦌'], ['カレー', '🍛'], ['サラダ', '🥗'], ['ヘリコプター', '🚁'], ['クッキー', '🍪'],
    ['ハンバーガー', '🍔'], ['ノート', '📓'], ['ハサミ', '✂️'], ['テント', '⛺'],
  ];

  // むずかしさ: てんてん・ちいさい もじ・のばす ぼう が なく、3もじ いか なら「かんたん」
  const isEasy = w => {
    const h = toHira(w);
    return [...h].length <= 3 && [...h].every(c => BASIC.includes(c));
  };

  // 1もじだけ よむと へんに なる もじの よみかた
  const SAY = {
    'ぁ': 'ちいさい あ', 'ぃ': 'ちいさい い', 'ぅ': 'ちいさい う', 'ぇ': 'ちいさい え', 'ぉ': 'ちいさい お',
    'ゃ': 'ちいさい や', 'ゅ': 'ちいさい ゆ', 'ょ': 'ちいさい よ', 'っ': 'ちいさい つ', 'ー': 'のばす ぼう',
  };
  const sayChar = c => SAY[toHira(c)] || c;

  // かず あそびの よみかた
  const YOMI = ['ぜろ', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう', 'じゅう'];
  const mathSay = (a, op, b, ans) =>
    `${YOMI[a]} ${op === '+' ? 'たす' : 'ひく'} ${YOMI[b]} は${ans == null ? '？' : ' ' + YOMI[ans]}`;

  // ほめことば（おいわいの がめんで よむ）
  const PRAISE = ['ぜんぶ できた！', 'すごい！ 5こ できた！', 'じょうずに かけたね！', 'かずの めいじん！'];

  window.KANA = {
    BASIC_COLS: BASIC_COLS.map(cols), EXTRA_COLS: EXTRA_COLS.map(cols),
    BASIC, DAKU, SMALL, toKata, toHira, isEasy, sayChar, YOMI, mathSay, PRAISE,
    words: kata => (kata ? KATA_WORDS : HIRA_WORDS),
  };
})();
